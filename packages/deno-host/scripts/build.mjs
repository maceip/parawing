function denoHostPlugin() {
  const wasmRegPath = resolve(SRC_DIR, "wasm-bytes-registry.ts");
  const shimPath = resolve(SRC_DIR, "workers-compat-shim.ts");
  return {
    name: "parawing-deno-host",
    setup(pluginBuild) {
      pluginBuild.onResolve({ filter: /^cloudflare:workers$/ }, () => ({ path: shimPath }));
      pluginBuild.onLoad({ filter: /\.wasm$/ }, async (args) => {
        const raw = await readFile(args.path);
        const b64 = raw.toString("base64");
        const contents =
          `import { registerBundledWasmBytes } from ${JSON.stringify(wasmRegPath)};\n` +
          `const bytes = new Uint8Array(Buffer.from(${JSON.stringify(b64)}, "base64"));\n` +
          `const mod = new WebAssembly.Module(bytes);\n` +
          `registerBundledWasmBytes(mod, bytes);\n` +
          `export default mod;\n`;
        return { contents, loader: "js", resolveDir: dirname(args.path) };
      });
    },
  };
}

